//! 팔레트 (PMPALET/SPALET/LOGO_P 항목). 원작 FUN_00420600 → FUN_00480c59:
//! 3바이트 (B, R, G) 순, 각 값 >> 4 해서 4비트로 쓰고, 화면 팔레트에는 << 4 (8비트 모드).
//! 원작은 10..245 번만 바꾼다 (윈도 시스템 색 자리 제외).

pub type Palette = [[u8; 3]; 256];

/// 윈도 256색 시스템 팔레트의 고정 20색 (0..9, 246..255)
const SYS_LO: [[u8; 3]; 10] = [[0, 0, 0], [128, 0, 0], [0, 128, 0], [128, 128, 0], [0, 0, 128], [128, 0, 128], [0, 128, 128], [192, 192, 192], [192, 220, 192], [166, 202, 240]];
const SYS_HI: [[u8; 3]; 10] = [[255, 251, 240], [160, 160, 164], [128, 128, 128], [255, 0, 0], [0, 255, 0], [255, 255, 0], [0, 0, 255], [255, 0, 255], [0, 255, 255], [255, 255, 255]];

pub fn from_bytes(d: &[u8]) -> Palette {
    let mut p = [[0u8; 3]; 256];
    p[..10].copy_from_slice(&SYS_LO);
    p[246..].copy_from_slice(&SYS_HI);
    for (i, c) in p.iter_mut().enumerate().take(246).skip(10) {
        if let Some(s) = d.get(i * 3..i * 3 + 3) {
            *c = [(s[1] >> 4) << 4, (s[2] >> 4) << 4, (s[0] >> 4) << 4];
        }
    }
    p
}
